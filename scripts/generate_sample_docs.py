def _find_cn_font() -> str:
    """Windows 系统中文字体（优先黑体，ttf 兼容性最好）。"""
    for font in [
        "C:/Windows/Fonts/simhei.ttf",    # 黑体
        "C:/Windows/Fonts/simsun.ttc",    # 宋体
        "C:/Windows/Fonts/msyh.ttc",      # 微软雅黑
    ]:
        if Path(font).exists():
            return font
    raise FileNotFoundError("未找到 Windows 中文字体，无法生成 PDF 演示文档")


class CNDoc(FPDF):
    """中文 PDF 基类：注册系统中文字体，统一版式。"""

    def __init__(self, title: str):
        super().__init__()
        self.add_font("CN", "", _find_cn_font())
        self.set_auto_page_break(auto=True, margin=20)
        self.add_page()
        # 封面标题
        self.set_font("CN", size=22)
        self.ln(10)
        self.cell(0, 12, title, align="C", new_x="LMARGIN", new_y="NEXT")
        self.ln(6)

    def heading(self, text: str) -> None:
        self.set_font("CN", size=14)
        self.ln(4)
        self.cell(0, 8, text, new_x="LMARGIN", new_y="NEXT")
        self.ln(1)

    def body(self, text: str) -> None:
        self.set_font("CN", size=10.5)
        self.multi_cell(0, 6, text)
        self.ln(1)

    def table(self, headers: list[str], rows: list[list[str]]) -> None:
        """简单表格：表头加粗 + 单元格边框。"""
        col_w = 175 // len(headers)
        self.set_font("CN", size=9.5)
        # 表头
        self.set_fill_color(220, 220, 220)
        for h in headers:
            self.cell(col_w, 7, h, border=1, fill=True, align="C")
        self.ln()
        # 数据行
        for row in rows:
            for cell in row:
                self.cell(col_w, 7, cell, border=1)
            self.ln()
        self.ln(2)


